// cyrb53 (public domain, by bryc): fast 53-bit string hash, truncated to 40 bits for compact storage.
// The same function is used by the build scripts and the extension, so keep it stable:
// changing it invalidates every generated data file.
export const HASH_BITS = 40;
const MOD = 2 ** HASH_BITS;

export function hash40(str) {
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)) % MOD;
}
